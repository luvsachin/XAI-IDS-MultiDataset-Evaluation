"""
Build a compact Phase 1-3 results integration status file.
Run after scripts 08-13. This does not invent results; it checks which reviewer-facing
outputs have been generated and writes a manifest for manuscript integration.
"""
from pathlib import Path
import pandas as pd
ROOT=Path(__file__).resolve().parents[2]; METRICS=ROOT/"04_Results"/"metrics"; NOTES=ROOT/"07_Notes"; NOTES.mkdir(parents=True,exist_ok=True)
expected=[
"statistical_significance_summary.csv",
"cicids2017_credibility_audit_results.csv",
"shap_seed_stability_summary_extended.csv",
"shap_subsample_robustness_summary.csv",
"local_shap_case_index.csv",
"nsl_kdd_class_level_error_analysis.csv",
"mlp_baseline_results.csv",
"semantic_grouping_robustness.csv",
"system_hardware_report.csv",
"python_package_versions.csv"]
rows=[]
for f in expected:
    p=METRICS/f; rows.append({"artifact":f,"exists":p.exists(),"path":str(p),"rows":len(pd.read_csv(p)) if p.exists() else 0})
df=pd.DataFrame(rows); df.to_csv(METRICS/"phase123_artifact_manifest.csv", index=False)
md=["# Phase 1-3 reviewer-facing artifact manifest", "", "Generated by `14_build_phase123_latex_tables.py`.", "", df.to_markdown(index=False)]
(NOTES/"Phase_1_2_3_Artifact_Manifest.md").write_text("\n".join(md), encoding="utf-8")
print(df.to_string(index=False))
